import type { CanonicalMission } from '../config/missions.ts'

// Each incident changes the tactical choice and its aftermath, rather than
// rotating the same four faction moves past a different mission noun. The
// winner and draw clauses describe how the obstacle affects the contest;
// they do not assert that a particular objective was scored in the game.
export type EditorialBeat = {
  move: string
  aftermath: string
  winner: string
  draw: string
}

// Area of Interest also has four distinct incidents, even when its terrain
// and weather change. The outcome stays with the selected antenna problem;
// the runtime renderer supplies the scored ground from the location tag.
